def send_email_alert(receivers, subject, html_body, sender_email="", app_password=""):
    """
    Sends an HTML email to one or many recipients via Gmail SMTP.
    Sender credentials come from src/email_config.py (backend) unless passed explicitly.
    Falls back to Demo Preview mode if credentials are blank or SMTP is blocked.
    """
    from src.email_config import get_sender

    if isinstance(receivers, str):
        receivers = [receivers]
    receivers = [r.strip() for r in receivers if r and r.strip()]
    shown = ", ".join(receivers) if receivers else "(no recipients)"

    if not sender_email or not app_password:
        sender_email, app_password = get_sender()
    sender_email = sender_email.strip()
    app_password = app_password.strip().replace(" ", "")

    if not receivers:
        return False, "⚠️ No recipients saved. Add one in Alert Config.", html_body

    if not sender_email or not app_password:
        return (
            False,
            f"📨 Alert Dispatched to **{shown}** (Demo Mode — sender credentials are not set in `src/email_config.py`).",
            html_body
        )

    try:
        msg = MIMEMultipart("alternative")
        msg["Subject"] = subject
        msg["From"] = f"AI SOC Alert Engine <{sender_email}>"
        msg["To"] = ", ".join(receivers)
        msg.attach(MIMEText(html_body, "html"))

        with smtplib.SMTP("smtp.gmail.com", 587, timeout=10) as server:
            server.ehlo()
            server.starttls()
            server.login(sender_email, app_password)
            server.sendmail(sender_email, receivers, msg.as_string())

        return True, f"✅ Live SMTP Email successfully sent to **{shown}**!", html_body
    except Exception as e:
        return (
            False,
            f"⚠️ Live SMTP blocked/failed ({str(e)}). Switched to **Safe Demo Preview Mode** for **{shown}** below.",
            html_body
        )
